// Studiya bölməsi: ton, altyazı üslubu, fon (kitabxanadan şəkil), plan ölçüləri; seçimlər düzəliş faylına düşür
import { createRequire } from 'node:module';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const require = createRequire(import.meta.url);
const { chromium, devices } = require('playwright');
const [file, outJson] = process.argv.slice(2);
const browser = await chromium.launch();
const page = await (await browser.newContext({ ...devices['iPhone 13'] })).newPage();
const errors = []; page.on('pageerror', (e) => errors.push(e.message));
await page.goto('file://' + file);
await page.waitForFunction(() => window.__editor);
assert.ok(await page.isVisible('#studio >> text=Studiya'), 'Studiya bölməsi görünür');
const tones = await page.$$('#studio button[aria-label^="Ton "]');
assert.ok(tones.length >= 4, 'ton variantları');
await tones[tones.length - 1].click();
await page.click('#studio button:text-is("Kontur")');
await page.click('#studio button:text-is("Şəkil")');
const thumbs = await page.$$('#studio button[aria-label^="Fon "]');
assert.ok(thumbs.length >= 5, 'fon kitabxanası kiçik şəkillərlə');
await thumbs[1].click();
await page.click('#studio button:text-is("Sakit")');
const ed = await page.evaluate(() => window.__editor.edits());
assert.ok(ed.requests && ed.requests.variation && ed.requests.variation.primary, 'ton seçimi');
assert.equal(ed.requests.bg.mode, 'image');
assert.ok(ed.requests.bg.lib);
assert.equal(ed.requests.multicam, 'calm');
assert.equal(ed.state.subtitles.style.bg, 'none', 'altyazı kontur — dərhal');
fs.writeFileSync(outJson, JSON.stringify(ed));
assert.deepEqual(errors, [], errors.join('; '));
await browser.close();
console.log('[studiya] HAMISI KEÇDİ');
