import { createRequire } from 'node:module';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const require = createRequire(import.meta.url);
const { chromium, devices } = require('playwright');
const [file, outJson] = process.argv.slice(2);
const browser = await chromium.launch();
const page = await (await browser.newContext({ ...devices['iPhone 13'] })).newPage();
const errors = []; page.on('pageerror', (e) => errors.push(e.message));
await page.goto('file://' + file);
await page.waitForFunction(() => window.__editor);
const first = await page.evaluate(() => window.__editor.TL.videoClips(window.__editor.S.hist.present)[0].id);
await page.evaluate((id) => { const n = document.querySelector(`.clip[data-id="${id}"]`); const r = n.getBoundingClientRect();
  n.dispatchEvent(new PointerEvent('pointerdown', { bubbles: true, pointerType: 'touch', clientX: r.left + 8, clientY: r.top + 6 })); }, first);
const setR = (label, v) => page.evaluate(([l, v]) => { const i = document.querySelector(`#sel input[aria-label="${l}"]`); i.value = String(v); i.dispatchEvent(new Event('change')); }, [label, v]);
const before = await page.evaluate(() => JSON.stringify(window.__editor.S.hist.present.clips.filter((c) => c.track !== 'v1').map(({ manual, origin, ...r }) => r)));
await setR('Yaxınlaşma', 1.3);
await setR('Üfüqi yer', 0.45);
await page.check('#mirClip');
await page.click('#sel >> text=İsti');
await setR('Yumşaltma', 0.3);
const c = await page.evaluate((id) => window.__editor.S.hist.present.clips.find((x) => x.id === id), first);
assert.equal(c.frame.mode, 'manual');
assert.ok(Math.abs(1 / c.frame.s - 1.3) < 0.02 && c.frame.keys[0].cx === 0.45);
assert.deepEqual([c.adjust.mirror, c.adjust.temperature, c.adjust.saturation, c.adjust.soften], [true, 5400, 1.08, 0.3]);
const after = await page.evaluate(() => JSON.stringify(window.__editor.S.hist.present.clips.filter((c) => c.track !== 'v1').map(({ manual, origin, ...r }) => r)));
assert.equal(after, before, 'görüntü dəyişikliyi yazılara/səsə toxunmur');
const tf = await page.evaluate(() => [document.querySelector('#vid').style.transform, document.querySelector('#vid').style.filter]);
assert.ok(tf[0].includes('scaleX(-1)') && tf[1].includes('sepia') && tf[1].includes('blur'));
console.log('[görüntü]', JSON.stringify({ s: c.frame.s, cx: c.frame.keys[0].cx, adjust: c.adjust }), tf);
fs.writeFileSync(outJson, JSON.stringify(await page.evaluate(() => window.__editor.edits())));
assert.deepEqual(errors, [], errors.join('; '));
await browser.close();
console.log('[görüntü] HAMISI KEÇDİ');
